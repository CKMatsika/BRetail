import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
test('purchasing and customer credit complete with reconciled balances', async ({page},info)=>{
 test.setTimeout(180000);
 await page.goto('/register');
 await page.getByLabel('Your name',{exact:true}).fill('Trade Owner');
 await page.getByLabel('Email address',{exact:true}).fill(`trade-${Date.now()}-${info.project.name}@example.test`);
 await page.getByLabel('Password · 12+ characters, letters and numbers').fill('SecurePassword123');
 await page.getByLabel('Confirm password').fill('SecurePassword123');
 await page.getByRole('button',{name:'Continue',exact:true}).click();
 await page.getByLabel('Business name',{exact:true}).fill('Trade Validation Shop');
 await page.getByRole('button',{name:'Continue',exact:true}).click();
 await page.getByRole('button',{name:'Create my workspace',exact:true}).click();
 await expect(page).toHaveURL('/dashboard');
 await page.goto('/modules');
 for(const name of ['inventory','accounting & finance','purchasing','sales & customers']){
  await page.getByRole('button',{name:'Enable '+name,exact:true}).click();
  await expect(page.getByRole('button',{name:'Disable '+name,exact:true})).toBeVisible();
 }
 await page.goto('/accounting');await page.getByRole('button',{name:'Initialize accounting',exact:true}).click();
 await expect(page.getByRole('button',{name:'Run reports',exact:true})).toBeVisible();
 const token=(await page.context().cookies()).find(c=>c.name==='XSRF-TOKEN')!;
 const headers={'X-XSRF-TOKEN':decodeURIComponent(token.value),Accept:'application/json'};
 const post=async(url:string,data:unknown)=>{const r=await page.request.post(url,{headers,data});expect(r.ok(),await r.text()).toBeTruthy();return (await r.json()).data;};
 const data=(await (await page.request.get('/accounting/data')).json()).data;
 const account=(role:string)=>data.mappings.find((m:{role:string})=>m.role===role).account_id;
 await post('/accounting/journals',{request_id:randomUUID(),book:'training',branch_id:data.branches[0].id,date:data.today,reference:'CAPITAL',description:'Owner funds',cashflow:'financing',lines:[{account_id:account('cash_safe'),debit:'50',credit:'0'},{account_id:account('opening_equity'),debit:'0',credit:'50'}]});
 const p=await post('/inventory/products',{name:'Trade Shirt',unit:'each',tax_class:'zero',warranty_months:0,active:true,attributes:[]});
 await post(`/inventory/products/${p.id}/variants`,{name:'Standard',sku:'TRADE-SHIRT',cost_price:'5',selling_price:'10',wholesale_price:'10',minimum_stock:'0',reorder_level:'0',active:true,attributes:[]});
 await page.goto('/purchasing');
 const form=(name:string|RegExp)=>page.locator('form').filter({has:page.getByRole('heading',{name,exact:typeof name==='string'})});
 const save=async(name:string|RegExp,button:string)=>{const f=form(name);await f.getByRole('button',{name:button,exact:true}).click();await expect(f.getByRole('status')).toHaveText('Saved successfully.');};
 await form('Create supplier').getByLabel('Supplier code',{exact:true}).fill('SUP');
 await form('Create supplier').getByLabel('Supplier name',{exact:true}).fill('Shirt Supplier');
 await save('Create supplier','Save');
 await page.getByRole('button',{name:'Orders',exact:true}).click();
 await page.getByLabel('Quantity 1',{exact:true}).fill('4');await page.getByLabel('Unit cost 1',{exact:true}).fill('5');
 await save('Create purchase order','Create order');
 await page.getByRole('button',{name:'Approve',exact:true}).click();
 await expect(page.getByRole('button',{name:'Receive goods',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Receive goods',exact:true}).click();
 await form(/^Receive PO/).getByLabel('Reference',{exact:true}).fill('DELIVERY-1');await page.getByLabel('Quantity 1',{exact:true}).fill('4');
 await save(/^Receive PO/,'Post goods receipt');
 await page.getByRole('button',{name:'Match supplier bill',exact:true}).click();
 await form(/^Bill against/).getByLabel('Reference',{exact:true}).fill('SUP-INVOICE-1');await page.getByLabel('Quantity 1',{exact:true}).fill('4');
 await save(/^Bill against/,'Post supplier bill');
 await page.getByRole('button',{name:'Pay bill',exact:true}).click();
 await form(/^Settle/).getByLabel('Reference',{exact:true}).fill('SUP-PAY-1');
 await form(/^Settle/).getByLabel('Settlement cash / bank account').selectOption(String(account('cash_safe')));
 await save(/^Settle/,'Post payment');
 await page.getByRole('button',{name:'Customers',exact:true}).click();
 await form('Create customer').getByLabel('Customer name',{exact:true}).fill('Credit Customer');await save('Create customer','Save');
 await form('Customer credit settings').getByLabel('Credit limit',{exact:true}).fill('100');await save('Customer credit settings','Save');
 await page.getByRole('button',{name:'Quotes',exact:true}).click();
 await form('Create sales quotation').getByLabel('Reference',{exact:true}).fill('QUOTE-1');await page.getByLabel('Quantity 1',{exact:true}).fill('2');
 await save('Create sales quotation','Save quotation');
 await page.getByRole('button',{name:'Accept and invoice',exact:true}).click();await save(/^Invoice accepted/,'Accept quote and post credit invoice');
 await page.getByRole('button',{name:'Return unpaid items',exact:true}).click();
 await form(/^Credit return/).getByLabel('Reference',{exact:true}).fill('RETURN-1');await form(/^Credit return/).getByLabel('Return reason').fill('Wrong size');await page.getByLabel('Quantity 1',{exact:true}).fill('1');await save(/^Credit return/,'Post credit return');
 await page.getByRole('button',{name:'Invoices',exact:true}).click();await page.getByRole('button',{name:'Receive payment',exact:true}).click();
 await form(/^Settle/).getByLabel('Reference',{exact:true}).fill('CUSTOMER-PAY-1');await form(/^Settle/).getByLabel('Settlement cash / bank account').selectOption(String(account('cash_safe')));await save(/^Settle/,'Post payment');
 const popup=page.waitForEvent('popup');await page.getByRole('link',{name:'Print',exact:true}).first().click();const print=await popup;await expect(print.getByText('Credit Customer',{exact:false}).first()).toBeVisible();await print.close();
 await page.getByRole('button',{name:'Aging',exact:true}).click();
 await expect(page.getByText(/Unallocated 0.0000/)).toHaveCount(2);
 await expect(page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).resolves.toBeTruthy();
 await page.screenshot({path:`test-results/trade-${info.project.name}.png`,fullPage:true});
});
